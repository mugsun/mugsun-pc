#!/bin/sh
# 根据 MUGSUN_GATEWAY_CIDRS 生成前置网关信任配置（http 级）：
#   - realip：只对来自网关网段的请求，用 X-Forwarded-For 还原真实客户端到 $remote_addr
#   - $mugsun_from_gateway：来自网关时才透传 X-Forwarded-Proto
# 变量为空时不信任任何前置代理。
set -eu
out=/etc/nginx/conf.d/00-mugsun-gateway.conf
{
  echo "# generated by 15-mugsun-gateway.sh"
  echo "geo \$realip_remote_addr \$mugsun_from_gateway {"
  echo "  default 0;"
  for c in $(echo "${MUGSUN_GATEWAY_CIDRS:-}" | tr ',;' '  '); do echo "  $c 1;"; done
  echo "}"
  for c in $(echo "${MUGSUN_GATEWAY_CIDRS:-}" | tr ',;' '  '); do echo "set_real_ip_from $c;"; done
  echo "real_ip_header X-Forwarded-For;"
  echo "real_ip_recursive on;"
} > "$out"
echo "15-mugsun-gateway.sh: trusted gateways: ${MUGSUN_GATEWAY_CIDRS:-<none>}"
