#!/bin/sh
# 启动前校验并生成前置网关信任配置（http 级）。任何非法值都直接退出，容器拒绝启动。
#   MUGSUN_GATEWAY_CIDRS：前置网关网段（逗号/分号/空白分隔）。拒绝 0.0.0.0/0、IPv4 前缀 </8、IPv6 前缀 </32。
#     - realip：只对来自这些网段的请求，用 X-Forwarded-For 还原真实客户端到 $remote_addr
#     - $mugsun_from_gateway：来自网关时才透传 X-Forwarded-Proto
#   MUGSUN_CSP_TILE_HOSTS / MUGSUN_CSP_TRACK_HOSTS：只允许 [A-Za-z0-9.*:/-] 与空格（防止 ; " 注入 CSP 头）。
#   MUGSUN_CSP_MODE：report-only（默认，只报告不拦截）| enforce（下发 Content-Security-Policy，
#     并附加一份更严的 Content-Security-Policy-Report-Only 用于观察下一轮收紧）。
#   MUGSUN_CSP_REPORT_URI：违规报告收集地址；为空时不输出 report-uri / report-to。
# 变量为空时不信任任何前置代理。
set -eu

die() { echo "15-mugsun-gateway.sh: $*" >&2; exit 1; }

valid_v4() {
  ip=$1
  echo "$ip" | grep -Eq '^([0-9]{1,3}\.){3}[0-9]{1,3}$' || return 1
  old_ifs=$IFS; IFS=.; set -- $ip; IFS=$old_ifs
  for o in "$@"; do [ "$o" -le 255 ] || return 1; done
}

check_cidr() {
  c=$1
  case "$c" in
    */*) addr=${c%/*}; pfx=${c#*/} ;;
    *) addr=$c; pfx= ;;
  esac
  [ -z "$pfx" ] || echo "$pfx" | grep -Eq '^[0-9]{1,3}$' || die "非法 CIDR 前缀：$c"
  case "$addr" in
    *:*)
      echo "$addr" | grep -Eq '^[0-9A-Fa-f:.]+$' || die "非法 IPv6 地址：$c"
      [ -z "$pfx" ] && pfx=128
      [ "$pfx" -le 128 ] || die "非法 IPv6 前缀：$c"
      [ "$pfx" -ge 32 ] || die "IPv6 网段过宽（前缀须 >= /32）：$c"
      ;;
    *)
      valid_v4 "$addr" || die "非法 IPv4 地址：$c"
      [ -z "$pfx" ] && pfx=32
      [ "$pfx" -le 32 ] || die "非法 IPv4 前缀：$c"
      [ "$pfx" -ge 8 ] || die "IPv4 网段过宽（前缀须 >= /8，禁止 0.0.0.0/0）：$c"
      ;;
  esac
}

for v in MUGSUN_CSP_TILE_HOSTS MUGSUN_CSP_TRACK_HOSTS; do
  eval "val=\${$v:-}"
  case "$val" in *[!A-Za-z0-9.*:/\ -]*) die "$v 含非法字符（只允许 A-Z a-z 0-9 . * : / - 和空格）：$val" ;; esac
done

csp_mode=${MUGSUN_CSP_MODE:-report-only}
case "$csp_mode" in
  report-only|enforce) ;;
  *) die "MUGSUN_CSP_MODE 只能是 report-only 或 enforce：$csp_mode" ;;
esac
csp_report_uri=${MUGSUN_CSP_REPORT_URI:-}
case "$csp_report_uri" in
  *[!A-Za-z0-9._~:/?=\&%@+-]*) die "MUGSUN_CSP_REPORT_URI 含非法字符（禁止空格、引号、分号等）：$csp_report_uri" ;;
esac

cidrs=$(echo "${MUGSUN_GATEWAY_CIDRS:-}" | tr ',;' '  ')
for c in $cidrs; do check_cidr "$c"; done

out=/etc/nginx/conf.d/00-mugsun-gateway.conf
{
  echo "# generated by 15-mugsun-gateway.sh"
  echo "geo \$realip_remote_addr \$mugsun_from_gateway {"
  echo "  default 0;"
  for c in $cidrs; do echo "  $c 1;"; done
  echo "}"
  for c in $cidrs; do echo "set_real_ip_from $c;"; done
  echo "real_ip_header X-Forwarded-For;"
  echo "real_ip_recursive on;"
} > "$out"
echo "15-mugsun-gateway.sh: trusted gateways: ${cidrs:-<none>}"

# ---- CSP ----
# 不含 'unsafe-eval' / 'wasm-unsafe-eval' / https: 通配。style-src 'unsafe-inline' 为 Element Plus 运行时内联样式所需；
# Cesium 需要 worker-src blob:；xgplayer（MSE）需要 media-src blob:。地图瓦片走同源 /api 代理，外域按需经 MUGSUN_CSP_TILE_HOSTS 追加。
tile=${MUGSUN_CSP_TILE_HOSTS:-}
track=${MUGSUN_CSP_TRACK_HOSTS:-}
csp_policy() {
  # $1 = style-src 取值
  p="default-src 'self'; script-src 'self'; style-src $1; img-src 'self' data: blob: $tile; font-src 'self' data:; connect-src 'self' $tile $track; worker-src 'self' blob:; child-src 'self' blob:; frame-src 'self'; media-src 'self' blob:; manifest-src 'self'; object-src 'none'; base-uri 'self'; form-action 'self'; frame-ancestors 'self'"
  if [ -n "$csp_report_uri" ]; then p="$p; report-uri $csp_report_uri; report-to csp"; fi
  # 压缩多余空格
  echo "$p" | tr -s ' ' | sed 's/ ;/;/g'
}
base=$(csp_policy "'self' 'unsafe-inline'")
strict=$(csp_policy "'self'")
csp_out=/etc/nginx/conf.d/csp-headers.inc
{
  echo "# generated by 15-mugsun-gateway.sh (MUGSUN_CSP_MODE=$csp_mode)"
  if [ -n "$csp_report_uri" ]; then
    echo "add_header Reporting-Endpoints 'csp=\"$csp_report_uri\"' always;"
  fi
  if [ "$csp_mode" = enforce ]; then
    echo "add_header Content-Security-Policy \"$base\" always;"
    echo "add_header Content-Security-Policy-Report-Only \"$strict\" always;"
  else
    echo "add_header Content-Security-Policy-Report-Only \"$base\" always;"
  fi
} > "$csp_out"
echo "15-mugsun-gateway.sh: CSP mode: $csp_mode, report-uri: ${csp_report_uri:-<none>}"
